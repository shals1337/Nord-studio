// ===== Apply / switch language =====
(function () {
  "use strict";
  var SUPPORTED = ["da", "en"];

  function apply(lang) {
    if (SUPPORTED.indexOf(lang) === -1) lang = "da";
    var dict = window.I18N[lang];
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = dict[el.getAttribute("data-i18n")];
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      var v = dict[el.getAttribute("data-i18n-ph")];
      if (v != null) el.setAttribute("placeholder", v);
    });
    if (dict["meta.title"] && document.body.dataset.page !== "sub") document.title = dict["meta.title"];

    document.querySelectorAll(".stat-num").forEach(function (el) {
      if (el.dataset.counted === "1") {
        el.textContent = el.getAttribute("data-count") + (el.getAttribute("data-suffix-" + lang) || "");
      }
    });

    document.querySelectorAll(".lang-toggle [data-lang]").forEach(function (s) {
      s.classList.toggle("active", s.getAttribute("data-lang") === lang);
    });

    try { localStorage.setItem("nordlang", lang); } catch (e) {}
  }

  var initial;
  try { initial = localStorage.getItem("nordlang"); } catch (e) {}
  if (!initial) {
    initial = (navigator.language || "da").toLowerCase().indexOf("da") === 0 ? "da" : "en";
  }
  apply(initial);

  document.addEventListener("DOMContentLoaded", function () {
    apply(document.documentElement.lang);
    var toggle = document.querySelector(".lang-toggle");
    if (toggle) {
      toggle.addEventListener("click", function () {
        apply(document.documentElement.lang === "en" ? "da" : "en");
      });
    }
  });

  window.NordLang = { apply: apply, current: function () { return document.documentElement.lang === "en" ? "en" : "da"; } };
})();
